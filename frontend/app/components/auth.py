import hashlib
import hmac
import os
import psycopg
import streamlit as st
from utilities.rds_utils import create_db_connection


def _password_digest(password: str, salt: bytes) -> bytes:
    return hashlib.scrypt(
        password.encode("utf-8"), salt=salt, n=2**15, r=8, p=3,
        dklen=32, maxmem=128 * 1024 * 1024,
    )


def hash_password(password: str) -> str:
    """Create a salted scrypt hash for the authentication.password column."""
    salt = os.urandom(16)
    return f"scrypt${salt.hex()}${_password_digest(password, salt).hex()}"


def verify_password(password: str, stored_hash: str) -> bool:
    """Verify a password against a hash generated by hash_password."""
    try:
        algorithm, salt_hex, digest_hex = stored_hash.split("$")
        salt = bytes.fromhex(salt_hex)
        expected = bytes.fromhex(digest_hex)
        if algorithm != "scrypt" or len(salt) != 16 or len(expected) != 32:
            return False
        return hmac.compare_digest(_password_digest(password, salt), expected)
    except (ValueError, TypeError):
        return False


def authenticate_user(username: str, password: str) -> bool:
    """Look up a user in RDS and verify their password without committing."""
    with create_db_connection(
        host=os.environ["DB_HOST"],
        dbname=os.environ["DB_NAME"],
        user=os.environ["DB_USER"],
        password=os.environ["DB_PASSWORD"],
        port=int(os.environ.get("DB_PORT", "5432")),
    ) as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT password FROM authentication WHERE username = %s", (username,))
            row = cursor.fetchone()

    stored_hash = row["password"] if row else f"scrypt${'00' * 16}${'00' * 32}"
    return verify_password(password, stored_hash) and row is not None


def require_login() -> None:
    if st.session_state.get("authenticated"):
        with st.sidebar:
            st.write(f"Signed in as {st.session_state['username']}")
            if st.button("Sign out"):
                st.session_state.clear()
                st.rerun()
        return

    st.title("Sign in")
    with st.form("login", clear_on_submit=True):
        username = st.text_input("Username")
        password = st.text_input("Password", type="password")
        submitted = st.form_submit_button("Sign in", type="primary")

    if submitted:
        try:
            authenticated = authenticate_user(username, password)
        except (KeyError, ValueError, psycopg.Error):
            st.error("Sign-in is temporarily unavailable. Please contact an administrator.")
            st.stop()
        if authenticated:
            st.session_state["authenticated"] = True
            st.session_state["username"] = username
            st.rerun()
        st.error("Incorrect username or password.")
    st.stop()